//! Decode packed trellis tiles → row-major f16 blocks.

use half::f16;

use super::codebook::{CodebookMode, decode_3inst};
use super::perm::kernel_order_to_row_major_f16;
use super::trellis::unpack_trellis_tile;

/// Decode 256 kernel-order codewords to kernel-order f16 samples.
pub fn decode_codewords(codewords: &[u16; 256], mode: CodebookMode) -> [f16; 256] {
    let mut out = [f16::ZERO; 256];
    for (o, w) in out.iter_mut().zip(codewords.iter()) {
        *o = decode_3inst(*w, mode);
    }
    out
}

/// Decode one packed tile (on-disk u16 words) to a row-major 16×16 f16 block.
pub fn decode_packed_tile(
    packed_tile: &[u16],
    k: u32,
    mode: CodebookMode,
) -> Result<[[f16; 16]; 16], crate::exl3::trellis::TrellisError> {
    let cws = unpack_trellis_tile(packed_tile, k)?;
    let kernel = decode_codewords(&cws, mode);
    Ok(kernel_order_to_row_major_f16(&kernel))
}

