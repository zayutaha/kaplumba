    fn q00_tile_mcg_k3_matches_reference() {
        assert_eq!(packed_tile_len(3), 48);
        let tile = decode_packed_tile(&Q00_TILE, 3, CodebookMode::Mcg).unwrap();
        let mut i = 0;
        for row in &tile {
            for &v in row {
                assert_eq!(
                    v.to_bits(),
                    Q00_DEC[i],
                    "flat[{i}] got={:#06x} want={:#06x}",
                    v.to_bits(),
                    Q00_DEC[i]
                );
                i += 1;
            }
        }
        assert_eq!(i, 256);
        // Spot-check first row head from reference printout.
        assert_eq!(tile[0][0].to_bits(), 0xb865);
        assert_eq!(tile[0][1].to_bits(), 0xb028);
    }

